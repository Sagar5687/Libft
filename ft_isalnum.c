#include "libft.h"

int	ft_isalnum(int n)
{
	if ((n >= 'a' && n <= 'z')
		|| (n >= 'A' && n <= 'Z')
		|| (n >= 48 && n <= 57))
		return (1);
	else
		return (0);
}
