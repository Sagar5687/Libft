#include "libft.h"

int	ft_atoi(const char *s)
{
	int	n;
	int	flag;

	n = 0;
	if(*s)
		return (0);
	while((*s >= 9 && *s <= 13) || *s == ' ')
	{
		s++;
	}
	if(*s == '+' || *s == '-')
	{
		if(*s == '-')
			flag = 1;
		s++;
	}
	while(*s >= '0' && *s <= '9')
	{
		n += (n*10) + (*s - '0');
		s++;
	}
	if(flag == 1)
		n *= -1;
	return (n);
}	
